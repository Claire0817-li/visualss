/*
数学贡献法 + 组合模运算
【题目：奥数巨兽】
题目描述：
你拥有 N 只奥数巨兽，每只的攻击力为 Ai。
可以选择巨兽序列的任意非空子序列，并将它们逐一售出。
每当售出一只巨兽时，该子序列中所有剩余未售出的巨兽的攻击力，都会增加刚刚售出的那只巨兽的**当前攻击力**。
一个子序列的价值定义为：如果以最优的顺序售出该子序列中的其他巨兽，最后剩下的一只巨兽所能达到的最大攻击力。
计算该序列所有非空子序列的价值之和，结果对 998244353 取模。

算法类型：数学推导、贡献法、组合计数、模逆元、递推预处理
核心结论：
1. 最优策略：对于任意子序列，保留攻击力最小的元素，其余元素从大到小依次售出，最终攻击力最大。
2. 贡献法思想：不枚举所有子序列，单独计算每个元素对总答案的总贡献，总贡献 = 元素值 × 总权重系数。
3. 权重公式：将数组升序排序后，第 i 个元素（1下标）的总权重系数为 (3^(i-1) + 1) * 2^(n-i) / 2
4. 模逆元：模数 998244353 是质数，根据费马小定理，除以2等价于乘以 2^(mod-2) mod mod。
5. 总答案：ans = Σ( a[i] * 权重系数 ) mod 998244353

预处理原理：
递推预处理 2 和 3 的幂次数组，所有测试用例复用，O(1) 查询，避免重复调用快速幂。
时间复杂度：
- 预处理：O(N)，N 为数据上限 2e5
- 每组测试用例：O(n log n)，瓶颈为排序操作
空间复杂度：O(N)，存储幂次数组
*/

#include <bits/stdc++.h>
using namespace std;
using ll=long long;       
using vi=vector<int>;    
using vl=vector<ll>;     
using vvi=vector<vi>;    
using vvl=vector<vl>;   

const ll mod=998244353;   
const int N=2e5+5;       

// 快速幂函数：计算 (a^n) % mod
// 原理：将指数 n 拆分为二进制，通过底数平方逐步计算，时间复杂度 O(log n)
ll quickpow(ll a,ll n)
{
    ll res=1;              // 结果初始化为乘法单位元 1
    while(n>0)             // 当指数不为 0 时循环
    {
        if(n&1) res=res*a%mod;  // 若指数二进制最后一位为 1，将当前底数乘入结果，立即取模
        a=a*a%mod;             // 底数平方，对应指数右移一位
        n>>=1;                  // 指数右移一位，等价于整数除以 2
    }
    return res;            // 返回最终结果
}

vl pow3(N),pow2(N);       // pow3[i] 存储 3^i % mod；pow2[i] 存储 2^i % mod；预处理后直接查询

int main()
{
    ios::sync_with_stdio(false);  
    cin.tie(nullptr);             
    
    int t;  cin>>t;               // 读入测试用例的组数
    ll inv2=quickpow(2,mod-2);    // 费马小定理求 2 的模逆元，等价于模意义下的 1/2
    
    // 递推预处理 2 和 3 的幂次数组
    pow3[0]=1,pow2[0]=1;          // 任何数的 0 次方都是 1，作为递推的起点
    for(int i=1;i<N;i++)          // 从 1 次方开始递推到上限
    {
        pow3[i]=pow3[i-1]*3%mod;  // 3^i = 3^(i-1) * 3，每步取模防止数值溢出
        pow2[i]=pow2[i-1]*2%mod;  // 2^i = 2^(i-1) * 2，每步取模防止数值溢出
    }
    
    while(t--)                    // 循环处理每组测试用例
    {
        int n;  cin>>n;           // 读入当前组的巨兽数量
        vl a(n+1);                // 1 下标存储数组，a[0] 闲置不用，方便对应公式推导
        for(int i=1;i<=n;i++)  cin>>a[i];  // 读入每只巨兽的攻击力
        
        sort(a.begin()+1,a.end());  // 将数组从小到大排序（只排 [1,n] 有效区间）
                                    // 排序是贡献法的前提：权重系数由元素的大小排名决定
        
        ll ans=0;                  // 答案累加器，初始为 0
        for(int i=1;i<=n;i++)      // 枚举每个元素，计算其总贡献并累加到答案
        {
            ll l=(pow3[i-1]+1)%mod;  // 左边 i-1 个元素对应的权重和的分子部分：(3^(i-1) + 1)
            ll r=pow2[n-i];           // 右边 n-i 个元素的选法数：每个可选或不选，共 2^(n-i) 种
            // 总权重系数 = l * r / 2，模运算中除法转换为乘以逆元 inv2
            // 每步乘法后取模，防止连续乘法超出 long long 范围
            ans=(ans+a[i]*l%mod*r%mod*inv2%mod)%mod;
        }
        cout<<ans<<'\n'; 
    }
    return 0;
}
