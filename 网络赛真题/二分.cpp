/*
二分答案 + 数学可行性判定
【题目：ICPC训练题集分配】
题目描述：
有 S 道题，分为 7 类，分别对应不同的学生子集：
F1仅学生1可做、F2仅学生2可做、F3学生1&2可做、
F4仅学生3可做、F5学生1&3可做、F6学生2&3可做、F7三人都可做。
每道题必须分配给一名能解决它的学生，目标是最大化三名学生中解题数量的最小值（最大化最小值）。
输出这个最大可能的最小值。

算法类型：二分答案、数学可行性约束判定
核心思路：
1. 二分枚举答案 mid：验证是否存在分配方案，让三名学生每人至少分到 mid 道题。
2. 可行性判定：先计算每个学生的专属题数量，得到距离 mid 的缺口；
   再通过「总题量约束、单个学生可用资源约束、两两学生可用资源约束」三层数学条件，判断共享题能否补全所有缺口。
3. 无需模拟分配过程，纯数学计算 O(1) 完成判定，避免贪心顺序导致的分配错误。

时间复杂度：O(T * log S)，T 为测试用例数，S 为总题数，单次判定为常数时间。
*/

#include <bits/stdc++.h>
using namespace std;
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;

// f[1]~f[7] 对应题目中的 F1~F7 七类题的数量
// 下标映射：
// 1: 仅学生1可做  2: 仅学生2可做  3: 学生1、2共同可做
// 4: 仅学生3可做  5: 学生1、3共同可做  6: 学生2、3共同可做
// 7: 学生1、2、3都可做
vl f(8);

// 功能：判断是否存在合法分配，使得三名学生每人至少分到 mid 道题
bool check(ll mid)
{
    // 提取各类题数量，语义化命名
    ll only1 = f[1];   // 学生1的专属题（只能给1）
    ll only2 = f[2];   // 学生2的专属题（只能给2）
    ll only3 = f[4];   // 学生3的专属题（只能给3）
    ll o12 = f[3];     // 1、2共享的二元题（可分给1或2）
    ll o13 = f[5];     // 1、3共享的二元题（可分给1或3）
    ll o23 = f[6];     // 2、3共享的二元题（可分给2或3）
    ll all3 = f[7];    // 三人共享的三元题（可分给任意一人）

    // 每个学生距离 mid 的缺口：专属题不够的部分，需要用共享题补足
    // max(0LL, ...) 保证专属题已经超过mid时，缺口为0
    ll need1 = max(0LL, mid - only1);
    ll need2 = max(0LL, mid - only2);
    ll need3 = max(0LL, mid - only3);

    // 所有可用共享题的总数
    ll total_spare = o12 + o13 + o23 + all3;

    // 约束1：总缺口不能超过总共享题数，整体题量不足以补全所有缺口则直接不可行
    if(need1 + need2 + need3 > total_spare) return false;

    // 约束2：单个学生的缺口，不能超过他本人能用到的所有共享题总数
    // 学生1能用到的共享题：12共享 + 13共享 + 三人共享
    if(need1 > o12 + o13 + all3) return false;
    // 学生2能用到的共享题：12共享 + 23共享 + 三人共享
    if(need2 > o12 + o23 + all3) return false;
    // 学生3能用到的共享题：13共享 + 23共享 + 三人共享
    if(need3 > o13 + o23 + all3) return false;

    // 约束3：每两名学生的缺口之和，不能超过这两人能共同支配的所有共享题总数
    // 学生1+2的可用资源：12共享 + 13共享（仅1用） + 23共享（仅2用） + 三人共享
    if(need1 + need2 > o12 + o13 + o23 + all3) return false;
    // 学生1+3的可用资源：13共享 + 12共享（仅1用） + 23共享（仅3用） + 三人共享
    if(need1 + need3 > o12 + o13 + o23 + all3) return false;
    // 学生2+3的可用资源：23共享 + 12共享（仅2用） + 13共享（仅3用） + 三人共享
    if(need2 + need3 > o12 + o13 + o23 + all3) return false;

    // 所有约束都满足，mid 是可行的
    return true;
}

int main()
{
    ios::sync_with_stdio(false);  // 关闭 cin 与 stdio 同步，大幅提升大数据输入速度
    cin.tie(nullptr);             // 解除 cin 与 cout 的绑定，避免频繁刷新缓冲区

    int t;  cin>>t;               // 读入测试用例总数
    while(t--)                    // 循环处理每组测试用例
    {
        ll s;  cin>>s;            // 读入当前用例的总题数
        for(ll i=1;i<=7;i++)  cin>>f[i];  // 依次读入七类题的数量

        ll ans = 0;               // 记录最终的最大可行最小值
        ll l=0, r=s;              // 二分左右边界：最小0，最大不超过总题数s

        // 整数二分模板：最大化可行值
        while(l <= r)
        {
            ll mid = (l + r) >> 1;  // 取中间值（右移等价于除以2向下取整）
            if(check(mid))          // mid 可行，尝试更大的值
            {
                ans = mid;          // 更新答案
                l = mid + 1;        // 左边界右移，搜索更大的可行值
            }
            else                    // mid 不可行，缩小右边界
            {
                r = mid - 1;        // 右边界左移，搜索更小的值
            }
        }
        cout << ans << '\n';       // 输出答案，用'\n'代替endl避免刷新缓冲区，加速输出
    }
    return 0;
}
