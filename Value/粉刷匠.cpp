/*
算法标签：动态规划；区间DP；分组背包
【题目】P4158 [SCOI2009]粉刷匠
题目描述：
有 n 块木板，每块木板分为 m 个格子，每个格子有目标颜色0或1。
每次操作：选择同一块木板上一段连续的格子，全部涂成同一种颜色。
每个格子最多粉刷1次，总操作次数最多t次。
求最多能把多少格子粉刷成正确的目标颜色。

数据范围：1 ≤ n,m ≤ 50，1 ≤ t ≤ 2500

思路：
1.单块木板DP：dp[i][j][c] 一块木板前i格，刷j次，最后一段颜色c，最大正确格子数。
  两种转移：①延续上一段颜色，不增加粉刷次数；②新开一段，切换颜色，次数+1。
  预处理得到g[bz][k]：第bz块木板刷k次的最大收益。
2.分组背包：n块木板对应n组物品；每组选择j次粉刷，消耗j，收益g[bz][j]；总消耗不超过t求最大价值。
*/

#include <bits/stdc++.h>
using namespace std;
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;
int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n,m,t;  cin>>n>>m>>t;
    vector<string> a(n+1);
    //读入n块木板，a[1]~a[n]存储每块木板的01目标串
    for(int i=1;i<=n;i++)   cin>>a[i];
    /*
     * g[bz][k]：第bz块板子，一共刷k次，能得到的正确格子数量
     * bz：木板编号；k：粉刷次数；一块木板最多m次（一格刷一次）
     */
    vvi g(n+1,vi(m+1,0));
    g[0][0]=0;

    //====================第一部分：单块木板DP，预处理g数组====================
    for(int bz=1;bz<=n;bz++)
    {
        /*
         * dp[i][j][c]  单块木板内部DP
         * i：处理前i个格子
         * j：已经粉刷j次
         * c：最后一段粉刷的颜色，取值0或者1
         * 值：最大匹配正确格子数；-1代表该状态不可到达
         */
        vector<vector<vi>> dp(m+1,vector<vi>(m+1,vi(2,-1)));
        //初始状态：0个格子，刷0次。
        dp[0][0][0]=0,dp[0][0][1]=0;

        //遍历这块木板的每一个格子，i代表前i格
        for(int i=1;i<=m;i++)
        {
            //当前第i格的目标颜色，字符串下标i‑1
            int tail=a[bz][i-1]-'0';

            //枚举粉刷总次数j，最多m次
            for(int j=0;j<=m;j++)
            {
                // --------转移1：不新开一段，延续上一格的颜色，粉刷次数不变--------
                //延续最后一段颜色为0
                if(dp[i-1][j][0]!=-1)
                    dp[i][j][0]=max(dp[i][j][0],dp[i-1][j][0]+(tail==0));
                //延续最后一段颜色为1
                if(dp[i-1][j][1]!=-1)
                    dp[i][j][1]=max(dp[i][j][1],dp[i-1][j][1]+(tail==1));

                // --------转移2：新开一段粉刷，切换颜色，粉刷次数j+1 --------
                //上一段是颜色1，现在新开一段涂0，次数+1
                if(j>0&&dp[i-1][j-1][1]!=-1)
                    dp[i][j][0]=max(dp[i][j][0],dp[i-1][j-1][1]+(tail==0));
                //上一段是颜色0，现在新开一段涂1，次数+1
                if(j>0&&dp[i-1][j-1][0]!=-1)
                    dp[i][j][1]=max(dp[i][j][1],dp[i-1][j-1][0]+(tail==1));
            }
        }

        /*
         * 把单块木板dp结果存入g数组
         */
        for(int k=1;k<=m;k++)
        {
            g[bz][k]=max(dp[m][k-1][0],dp[m][k-1][1]);
            //不可达状态收益置0
            if(g[bz][k]==-1) g[bz][k]=0;
        }
    }

    //====================第二部分：分组背包DP====================
    /*
     * dp[bz][i]：处理前bz块木板，一共使用i次粉刷，得到最大正确格子数
     * -1标记状态不可达；dp[0][0]=0：0块木板，0次操作，收益0
     */
    vvi dp(n+1,vi(t+1,-1));
    dp[0][0]=0;

    //枚举每一块木板（每一组物品）
    for(int bz=1;bz<=n;bz++)
    {
        //倒序枚举总次数，分组背包倒序，保证每组只能选一个方案
        for(int i=t;i>=0;i--)
        {
            //j：当前这块木板分配j次粉刷；min(m,i)：木板最多m次，不能超过总次数i
            for(int j=0;j<=min(m,i);j++)
            {
                //如果前bz‑1块木板i‑j次的状态不可达，跳过
                if(dp[bz-1][i-j]==-1)   continue;
                //状态转移：前bz‑1块i‑j次 + 当前木板j次的收益
                dp[bz][i]=max(dp[bz][i],dp[bz-1][i-j]+g[bz][j]);
            }
        }
    }

    //答案：前n块木板，使用0~t次中，取最大收益
    int ans=0;
    for(int j=0;j<=t;j++)   ans=max(ans,dp[n][j]);
    cout<<ans;
    return 0;
}