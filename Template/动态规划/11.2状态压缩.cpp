/*
AcWing 291 蒙德里安的梦想
题目：用2×1 / 1×2的小矩形铺满 h行 w列 的大矩形，求铺放总方案数
多组输入，h=0 && w=0 结束；1 ≤ h,w ≤11

状压DP核心思想：
只考虑横向放置(1×2)的方块：方块占【本列】和【右边一列】。
二进制状态：一共h位，每一位对应一行。
bit = 1：代表该位置有方块从本列向右伸到下一列
bit = 0：该位置没有方块向外伸出

dp[i][j]含义：处理完前 i 列，第i列向i+1列伸出的状态为 j，总方案数

转移条件：从i‑1列状态k 转移到i列状态j
1. (j & k) == 0：k是i‑1列伸到i列；j是i列伸到i+1列。同一行不能同时为1，格子不能重叠冲突。
2. st[j | k] == true：k | j 代表本列被横方块占据的全部行；
   剩下bit=0是空位，空位只能放竖直2×1方块，因此连续的0段长度必须全部为偶数。

初始化：dp[0][0] = 1，0列之前，没有方块向外伸出，1种初始合法方案。
答案：dp[w][0]，全部w列处理完毕，最后一列不能再向右伸出方块，状态必须为0。
*/
#include <bits/stdc++.h>
using namespace std;
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int h,w;
    //读入行h、列w；h和w同时等于0才退出循环
    while(cin>>h>>w, h||w)
    {
        /*
        st数组预处理：st[s]=true 代表二进制s是合法状态
        s中所有连续0段的长度必须全部是偶数，才能放下竖直2×1方块
        */
        vector<bool> st(1 << h, true);
        for(int i = 0; i < (1 << h); i++)   // i遍历全部h位二进制状态
        {
            int cnt = 0;    // cnt统计当前连续0的个数
            for(int j = 0; j < h; j++)     // j遍历二进制每一位，对应每一行
            {
                if( (i >> j) & 1 )         // 当前bit等于1：遇到横方块占用该行
                {
                    // 碰到1，代表前面一段连续0到此结束；如果cnt是奇数，竖方块放不下，状态非法
                    if(cnt & 1)
                    {
                        st[i] = false;
                        break;
                    }
                    cnt = 0;    //碰到bit=1，清空连续0计数器
                }
                else
                {
                    cnt++;  //bit等于0，空位，连续0计数+1
                }
            }
            /*
            for循环结束后，有可能二进制末尾是一串连续0，后面再也没有bit=1触发上面的判断
            需要单独检查末尾这一段连续0，如果是奇数，状态非法
            */
            if(cnt & 1)
                st[i] = false;
        }

        // dp[i][j]：处理完前i列，第i列向外伸出状态j；long long防止方案数溢出
        vvl dp(w + 1, vl(1 << h, 0));
        dp[0][0] = 1;   // 初始状态：0列，没有方块向外伸出，方案数为1

        // i：枚举已经处理完 i 列
        for(int i = 1; i <= w; i++)
        {
            // j：第 i 列，向 i+1 列伸出的状态
            for(int j = 0; j < (1 << h); j++)
            {
                // k：第 i‑1 列，向 i 列伸出的状态（上一列的状态）
                for(int k = 0; k < (1 << h); k++)
                {
                    /*
                    转移条件：
                    1. (j & k) == 0：同一行不能同时被左边伸过来、又向右伸出去，禁止格子重叠
                    2. st[j | k]：合并k,j得到本列被横方块占用的位置，空位连续0全部偶数，合法
                    */
                    if( (j & k) == 0 && st[j | k] )
                    {
                        // 合法，把i‑1列状态k的全部方案累加给i列状态j
                        dp[i][j] += dp[i-1][k];
                    }
                }
            }
        }
        // w列全部铺完，最后一列不能向外伸出方块，状态必须是0，输出dp[w][0]
        cout << dp[w][0] << '\n';
    }
    return 0;
}
