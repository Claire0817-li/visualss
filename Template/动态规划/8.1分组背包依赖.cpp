/*
背包DP‑有依赖背包（主件附件，转化分组背包）
【题目：洛谷P1064 金明的预算方案】
题目描述：
一共n元预算，m个物品。每个物品有价格va，重要度wi。
物品分为主件和附件，g=0代表主件；g≠0代表附件，g是所属主件编号。
买附件必须先买对应的主件；每个主件最多带2个附件。
总价值 = 价格 × 重要度。求总预算不超过n时，最大总价值。

优化技巧：
价格全部除以10，缩小数据规模，减少数组开销。
对于每一个主件，一共有4种选择方案：
1. 只买主件
2. 买主件 + 附件1
3. 买主件 + 附件2
4. 买主件 + 附件1 + 附件2
把这4种方案当做分组背包里同一组的4件物品，每组4选1或者都不选。

状态定义：dp[j]：花费j*10元，可以获得的最大总价值
v[i][0],w[i][0]：第i个主件的体积、价值
v[i][1],w[i][1]：主件i的第一个附件
v[i][2],w[i][2]：主件i的第二个附件

循环逻辑：
外层遍历每一个主件；
j倒序循环（分组背包，01背包思想，防止重复选）；
枚举本组4种购买方案做max更新。
时间复杂度 O(m*n)
*/

#include <bits/stdc++.h>
using namespace std;

//类型别名简化书写
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll n,m;
    cin>>n>>m;
    n /= 10;   // 价格全部除以10，压缩背包体积，减少计算量

    // v[i][0]主件体积；v[i][1]附件1体积；v[i][2]附件2体积
    // w[i][0]主件价值；w[i][1]附件1价值；w[i][2]附件2价值
    vvl v(m+1, vl(3,0)),w(m+1, vl(3,0));

    for(ll i=1;i<=m;i++)
    {
        ll va,wi,g;
        cin>>va>>wi>>g;
        if(g == 0)
        {
            // g=0：这是主件
            v[i][0] = va / 10;
            w[i][0] = wi * va; //价值=价格×重要度
        }
        else
        {
            // g≠0：是附件，挂到主件g下面
            if(v[g][1] == 0)
            {
                //第一个附件存入下标1
                v[g][1] = va / 10;
                w[g][1] = wi * va;
            }
            else
            {
                //第二个附件存入下标2
                v[g][2] = va / 10;
                w[g][2] = wi * va;
            }
        }
    }

    vl dp(n+1); // dp[j]花费j*10元的最大价值，初始全部0

    //遍历每一个物品，只处理主件
    for(ll i=1;i<=m;i++)
    {
        if(v[i][0] == 0) continue; //不是主件，跳过（附件不单独处理）

        // j倒序，分组背包，防止同一主件的方案重复选取
        for(ll j = n; j >= 0; j--)
        {
            //方案1：只买主件
            if(j - v[i][0] >= 0)
                dp[j] = max(dp[j], dp[j - v[i][0]] + w[i][0]);

            //方案2：主件 + 附件1
            if(j - v[i][0] - v[i][1] >= 0)
                dp[j] = max(dp[j], dp[j - v[i][0] - v[i][1]] + w[i][0] + w[i][1]);

            //方案3：主件 + 附件2
            if(j - v[i][0] - v[i][2] >= 0)
                dp[j] = max(dp[j], dp[j - v[i][0] - v[i][2]] + w[i][0] + w[i][2]);

            //方案4：主件 + 附件1 + 附件2
            if(j - v[i][0] - v[i][1] - v[i][2] >= 0)
                dp[j] = max(dp[j], dp[j - v[i][0] - v[i][1] - v[i][2]] + w[i][0] + w[i][1] + w[i][2]);
        }
    }
    cout << dp[n];
    return 0;
}
