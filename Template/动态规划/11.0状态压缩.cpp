/*
算法：状态压缩DP（状压DP）
【洛谷 P1896 [SCOI2005]互不侵犯 小国王】
题目描述：
在 n×n 的棋盘里面放 k 个国王，国王可以攻击周围8个相邻格子（上下、左右、四个斜角）。
要求：任意两个国王不能互相攻击，求总共有多少种摆放方案。
数据范围：1 ≤ n ≤ 10，0 ≤ k ≤ n*n
输入格式：
一行两个整数 n,k
输出格式：
输出一个整数，代表合法方案总数
*/
#include <bits/stdc++.h>
using namespace std;
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n,k;    cin>>n>>k;
    vi s,num(1<<n);

    // ==========【预处理1：筛选单行合法状态】==========
    /*
    二进制mask理解：一行用一个整数i表示
    二进制位为1代表该位置放国王，0代表不放国王
    例 n=3，i=5 → 二进制 101，表示第0格、第2格放国王
    */
    for(int i=0;i<(1<<n);i++)
    {
        // !(i & (i>>1))：判断本行没有两个国王相邻
        // i>>1 所有位右移一位，如果有相邻1，按位与结果不为0
        if(!(i&(i>>1)))
            s.push_back(i); // s数组保存所有单行合法状态

        // num[i]：统计状态i里面有多少个国王（二进制里面1的个数）
        for(int j=0;j<n;j++)
        {
            num[i] += (i>>j & 1);
        }
    }

    int m = s.size(); // m：合法单行状态总个数

    // ==========【DP数组定义】==========
    /*
    dp[i][j][a]
        i：处理到第 i 行（1~n）
        j：棋盘上一共放置 j 个国王
        a：当前第 i 行选用 s[a] 这个合法状态，a是s数组的下标
        值：该状态下的摆放方案总数
    维度大小说明：
        n+2：行，多开2防止越界
        k+2：国王总数，最多放k个
        m：合法行状态的数量
    */
    vector<vector<vector<ll>>> dp(n+2,vector<vector<ll>>(k+2,vector<ll>(m,0)));

    // ==========【DP边界初始化】==========
    /*
    dp[0][0][0]=1
    虚拟第0行（不存在的行），放0个国王，选用s[0]=0（空状态，不放国王）
    含义：还没有处理任何行的时候，有且仅有1种方案：什么都不放
    ⚠️极其关键，如果不写这句，所有dp值全部为0，输出答案永远是0
    */
    dp[0][0][0]=1;

    // ==========【四层循环状态转移】==========
    for(int i=1;i<=n;i++)        // i：枚举当前处理第几行，从第1行到n行
    {
        for(int j=0;j<=k;j++)    // j：枚举棋盘累计使用国王总数量
        {
            for(int a=0;a<m;a++) // a：枚举【当前行】的合法状态下标
            {
                int cnt = num[s[a]]; // 当前行状态s[a]需要摆放cnt个国王
                if(j < cnt) continue;//剪枝：累计国王j还不够本行消耗cnt，直接跳过

                // b：枚举【上一行】的合法状态下标
                for(int b=0;b<m;b++)
                {
                    /*
                    判断上一行s[b] 和 当前行s[a] 是否可以上下相邻摆放
                    国王8方向不能攻击，两行之间需要检查3种冲突：
                    1. s[b] & s[a]        ：上下正对冲突，同一列两行都放国王
                    2. s[b] & (s[a]>>1)   ：当前行右移1位，检查 ↙ ↗ 斜对角冲突
                    3. s[b] & (s[a]<<1)   ：当前行左移1位，检查 ↘ ↖ 斜对角冲突
                    三个条件全部为0，代表两行摆放互不冲突，可以转移
                    */
                    if(!(s[b]&s[a])&&!(s[b]&(s[a]>>1))&&!(s[b]&(s[a]<<1)))
                    {
                        /*
                        状态转移方程
                        dp[i][j][a]：处理完第i行，一共j个国王，本行状态s[a]
                        来自：处理完i‑1行，一共 j‑cnt 个国王，上一行状态s[b]
                        本行消耗cnt个国王，所以上一层总国王数要减去cnt
                        把所有合法上一行的方案累加过来
                        */
                        dp[i][j][a] += dp[i-1][j-cnt][b];
                    }
                }
            }
        }
    }

    // ==========【统计最终答案】==========
    ll ans = 0;
    /*
    n行全部处理完成，总共放k个国王
    最后一行可以是任意合法状态a，把所有状态的方案全部累加
    */
    for(int a=0;a<m;a++)
        ans+=dp[n][k][a];

    cout<<ans;
    return 0;
}
