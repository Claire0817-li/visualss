/*
单调队列模板
【题目：P1886 滑动窗口 /【模板】单调队列】
题目描述：
给定长度为 n 的数组，固定窗口大小 k，窗口从左向右逐格滑动。
依次输出每个窗口内部的最小值；换行后再依次输出每个窗口内部的最大值。

算法类型：单调队列（数组模拟队列）
时间复杂度 O(n)，每个元素最多入队一次、出队一次。

核心要点：
1.队列 q 保存数组下标，**不存数值**，依靠下标判断元素是否滑出窗口。
2.求窗口最小值：维护队内下标对应的数值单调递增。
  新元素入队前，把队尾所有大于当前值的下标全部弹出。队头即为窗口最小值下标。
3.求窗口最大值：维护队内下标对应的数值单调递减。
  新元素入队前，把队尾所有小于当前值的下标全部弹出。队头即为窗口最大值下标。
4.当前窗口区间：[i‑k+1 , i]。如果队头下标小于窗口左边界，代表该元素已经离开窗口，队头后移。
5.只有 i >= k 的时候窗口才满，此时可以输出队头结果。
*/

#include <bits/stdc++.h>
using namespace std;
using ll=long long;
using vi=vector<int>;
using vl=vector<ll>;
using vvi=vector<vi>;
using vvl=vector<vl>;


int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll n,k; cin>>n>>k;   // n数组长度，k滑动窗口大小
    vl a(n+1);           // a[1~n]存储原始数组数据，下标从1开始
    for(ll i=1;i<=n;i++) cin>>a[i];


    vl q(n+1);  // q数组模拟单调队列，**存放原数组a的下标**，不是存数值
    ll h=1,t=0; // h队头指针，t队尾指针；[h,t]为队列有效区间，h>t代表队列为空


    // ==========第一遍：求每个窗口的最小值，维护单调递增队列==========
    for(int i=1;i<=n;i++)
    {
        // 队尾清理：队列不为空，且队尾对应数值 > 当前a[i]，弹出队尾
        // 比a[i]大的元素没有机会成为窗口最小值，直接舍弃，维持队列单调递增
        while(t>=h&&a[q[t]]>a[i])
            t--;

        q[++t]=i; // 当前元素下标i加入队尾

        // 队头清理：队头下标已经落在窗口左边界之外，队头出队
        // 当前窗口合法范围 [i‑k+1 , i]
        if(q[h]<i-k+1)
            h++;

        // i>=k：窗口长度达到k，队头就是当前窗口最小值的下标，输出
        if(i>=k)
            cout<<a[q[h]]<<" ";
    }
    cout<<"\n";


    h=1,t=0; // 重置队列头尾指针，复用q数组，清空队列状态

    // ==========第二遍：求每个窗口的最大值，维护单调递减队列==========
    for(int i=1;i<=n;i++)
    {
        // 队尾清理：队列不为空，队尾对应数值 < 当前a[i]，弹出队尾
        // 比a[i]小的元素没有机会成为窗口最大值，维持队列单调递减
        while(t>=h&&a[q[t]]<a[i])
            t--;

        q[++t]=i; // 当前下标入队尾

        // 队头清理：过期下标滑出窗口，队头后移
        if(q[h]<i-k+1)
            h++;

        // 窗口成型，输出窗口最大值
        if(i>=k)
            cout<<a[q[h]]<<" ";
    }

    return 0;
}
